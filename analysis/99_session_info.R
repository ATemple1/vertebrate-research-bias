## ============================================================================
## 99_session_info.R
##
## Records the computing environment. Finds every package the analysis
## scripts use (library() calls and pkg:: references), loads them, and writes
## session_info.txt to the repository root, including a ready-made package
## line for the README. Run last, after the final full run, and commit the
## result.
##
## Produces: session_info.txt
## ============================================================================

scripts <- list.files("analysis", pattern = "^[0-9]{2}_.*\\.R$", full.names = TRUE)
scripts <- scripts[basename(scripts) != "99_session_info.R"]

code <- unlist(lapply(scripts, readLines, warn = FALSE))
code <- sub("#.*$", "", code)                       # drop comments

attached <- gsub("library\\(\\s*['\"]?", "",
                 unlist(regmatches(code, gregexpr("library\\(\\s*['\"]?[A-Za-z][A-Za-z0-9.]*", code))))
namespaced <- unlist(regmatches(code, gregexpr("[A-Za-z][A-Za-z0-9.]*(?=:::?)", code, perl = TRUE)))
pkgs <- sort(unique(c(attached, namespaced)))

for (p in pkgs) suppressPackageStartupMessages(library(p, character.only = TRUE))

pkg_source <- function(p) {
  d <- packageDescription(p)
  if (identical(d$RemoteType, "github"))
    return(sprintf("GitHub %s/%s@%s", d$RemoteUsername, d$RemoteRepo, substr(d$RemoteSha, 1, 7)))
  if (identical(d$Repository, "CRAN")) return("CRAN")
  if (!is.null(d$biocViews) && nzchar(d$biocViews)) return("Bioconductor")
  if (identical(d$Priority, "base")) return("base R")
  if (!is.null(d$Repository)) return(d$Repository)
  "unknown"
}

info <- data.frame(
  package = pkgs,
  version = vapply(pkgs, function(p) packageDescription(p)$Version, ""),
  source  = vapply(pkgs, pkg_source, ""),
  row.names = NULL
)

writeLines(c(
  "Session information",
  "===================",
  "",
  sprintf("Generated by analysis/99_session_info.R on %s.", Sys.Date()),
  "",
  "Packages used by the analysis scripts",
  "-------------------------------------",
  sprintf("  %-20s %-12s %s", info$package, info$version, info$source),
  "",
  "README line",
  "-----------",
  paste(sprintf("`%s` (%s)", info$package, info$version), collapse = ", "),
  "",
  "sessionInfo()",
  "-------------",
  capture.output(sessionInfo())
), "session_info.txt")
